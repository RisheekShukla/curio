// Generates supabase/seed.sql from the curated seed library. Re-runnable: upserts on slug.
// Usage: node scripts/generate-seed-sql.ts   (Node 22.18+ / 24 runs TypeScript natively)
import { writeFileSync } from "node:fs";
import { SEED_DISCOVERIES } from "../src/lib/content/seed-discoveries.ts";

const lit = (v: string | number | null | undefined): string =>
  v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`;
const arr = (values: string[]) => (values.length ? `array[${values.map(lit).join(", ")}]::text[]` : "'{}'::text[]");

const rows = SEED_DISCOVERIES.map((d) =>
  [
    lit(d.slug),
    lit(d.title),
    lit(d.summary),
    lit(d.category),
    arr(d.tags),
    lit(d.image?.url),
    lit(d.image?.alt),
    lit(d.image?.credit),
    lit(d.image?.license),
    lit(d.image?.licenseUrl),
    lit(d.image?.sourcePageUrl),
    arr(d.starterQuestions),
    lit(d.source?.title),
    lit(d.source?.url),
    lit(d.readingMinutes),
    lit(d.status),
  ].join(",\n    "),
);

const sql = `-- Generated by scripts/generate-seed-sql.ts. Do not edit by hand.
-- Safe to run repeatedly: existing discoveries are updated in place by slug.
insert into public.discoveries (
  slug, title, summary, category, tags,
  image_url, image_alt, image_credit, image_license, image_license_url, image_source_url,
  starter_questions, source_title, source_url, reading_minutes, status
) values
${rows.map((r) => `  (\n    ${r}\n  )`).join(",\n")}
on conflict (slug) do update set
  title = excluded.title,
  summary = excluded.summary,
  category = excluded.category,
  tags = excluded.tags,
  image_url = excluded.image_url,
  image_alt = excluded.image_alt,
  image_credit = excluded.image_credit,
  image_license = excluded.image_license,
  image_license_url = excluded.image_license_url,
  image_source_url = excluded.image_source_url,
  starter_questions = excluded.starter_questions,
  source_title = excluded.source_title,
  source_url = excluded.source_url,
  reading_minutes = excluded.reading_minutes,
  status = excluded.status;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${SEED_DISCOVERIES.length} discoveries to supabase/seed.sql`);
